// ---------- บรรยายคดีจาก "ข้อเท็จจริง" ที่เอนจินคำนวณแล้ว ----------
// ctx: { victim:{nickname}, killer:{nickname}|null, cause:'attack'|'trap'|'defense'|'objective'|'wrongTarget', weapon:{name,kind}|null,
//        zone:{name}, day, messy, moved, witnesses:[nick], discoveredZone:{name} }
export function mockNarrateCase(ctx) {
  const { victim, killer, cause, weapon, day, messy, moved } = ctx;
  const v = victim.nickname;
  // ชื่อห้องในประโยค: เว้นวรรคท้ายถ้าลงท้ายด้วยตัวเลข ("ชั้น 1" + "ใน" → "ชั้น 1 ใน")
  const zone = { name: /[0-9A-Za-z]$/.test(ctx.zone?.name || '') ? `${ctx.zone.name} ` : ctx.zone?.name || '?' };
  const kind = weapon?.kind || 'none';
  const wname = weapon?.name || '';
  let bodyState;
  let title;
  if (cause === 'objective') {
    title = pick(['ร่างที่เงียบงัน', 'ความตายที่ไม่มีคำอธิบาย', 'ผู้ที่ไม่ได้กลับมา']);
    bodyState = `${v}นอนตะแคงราวกับหลับ ไม่มีบาดแผลภายนอกที่มองเห็น ใบหน้าซีดและมือกำแน่น ไม่มีร่องรอยการต่อสู้รอบตัวเลย`;
  } else if (cause === 'trap' && kind === 'poison') {
    title = pick(['รสขมในแก้วน้ำ', 'ลมหายใจสุดท้ายที่${zone}'.replace('${zone}', zone.name), 'ของขวัญที่ไม่มีใครส่ง']);
    bodyState = `${v}ล้มอยู่ข้างโต๊ะ ริมฝีปากเขียวคล้ำ มีแก้วน้ำล้มคว่ำอยู่ใกล้มือ ไม่มีบาดแผลภายนอก`;
  } else if (cause === 'trap') {
    title = pick(['กับดักในความเงียบ', `เสียงดังจาก${zone.name}`, 'สิ่งที่รออยู่หลังประตู']);
    bodyState = `${v}นอนคว่ำอยู่ใต้${wname}ที่ตกลงมา มีแผลแตกที่ศีรษะ ดูเหมือนถูกของหนักกระแทกขณะกำลังเปิดหรือหยิบอะไรบางอย่าง`;
  } else if (kind === 'poison') {
    title = pick(['ยาพิษใต้ลิ้น', 'มื้อสุดท้าย', 'ความตายไร้เสียง']);
    bodyState = `${v}นั่งพิงผนังตาเบิกโพลง ริมฝีปากเขียวคล้ำ ไม่มีบาดแผลภายนอก มีกลิ่นเคมีจาง ๆ จากปาก`;
  } else if (/ปืน|ธนู|ฉมวก/.test(wname)) {
    title = pick(['เสียงดังเพียงครั้งเดียว', 'นัดที่ไม่มีใครได้ยิน', 'ระยะประชิด']);
    bodyState = `${v}นอนหงาย มีบาดแผลทะลุที่หน้าอก${/ปืน/.test(wname) ? ' และคราบเขม่ารอบแผล' : ''} เลือดเป็นวงกว้างใต้ตัว`;
  } else if (/มีด|กรรไกร|ขวาน|แหลม|เชิงเทียน|ผ่าตัด/.test(wname)) {
    title = pick(['คมมีดในที่แคบ', 'รอยบาดที่ชายโครง', 'เลือดบนพื้นเย็น']);
    bodyState = `${v}นอนตะแคง มีบาดแผลลึกที่ชายโครงและลำคอ คราบเลือดแห้งเป็นวงกว้าง${messy ? ' รอบตัวมีของล้มระเนระนาดเหมือนมีการต่อสู้' : ' รอบตัวแทบไม่มีร่องรอยการต่อสู้'}`;
  } else if (/เชือก|ม่าน|ผ้า|สายไฟ|ชูชีพ/.test(wname)) {
    title = pick(['รอยรัดบนลำคอ', 'ลมหายใจที่ถูกพราก', 'เงียบจนน่ากลัว']);
    bodyState = `${v}นอนหงาย มีรอยรัดเป็นเส้นรอบลำคอ ปลายนิ้วมีรอยถลอกราวกับพยายามดึงอะไรออก`;
  } else if (cause === 'defense') {
    title = pick(['ผู้ล่าที่กลายเป็นเหยื่อ', 'แผนที่ย้อนศร', 'การต่อสู้ในความมืด']);
    bodyState = `${v}นอนคว่ำ มีรอยช้ำหลายแห่งและแผลที่ท้ายทอย ข้อนิ้วถลอกเหมือนเพิ่งต่อยอะไร มีร่องรอยการต่อสู้ชัดเจนรอบตัว`;
  } else {
    title = pick(['ของหนักจากด้านหลัง', 'ศพในความเงียบ', `เงาที่${zone.name}`]);
    bodyState = `${v}นอนคว่ำหน้า มีรอยช้ำและแผลแตกที่ท้ายทอย เลือดไหลเป็นทางสั้น ๆ${messy ? ' ของรอบตัวล้มกระจัดกระจาย' : ''}`;
  }
  const sceneNotes = [
    moved ? `มีรอยลากจาง ๆ บนพื้นนำมาถึงจุดที่พบศพ ดูเหมือนร่างถูกย้ายมาจากที่อื่น` : `ไม่มีร่องรอยว่าร่างถูกเคลื่อนย้าย`,
    cause === 'objective' ? 'ไม่พบสิ่งผิดปกติอื่นรอบศพ' : messy ? 'มีคราบและรอยเปื้อนหลายจุดที่คนลงมือไม่ได้เก็บ' : 'ที่เกิดเหตุค่อนข้างเรียบร้อย คนลงมือดูใจเย็น',
  ].join(' ');
  const k = killer?.nickname;
  const truthSummary =
    cause === 'objective'
      ? `${v}ไม่ได้ถูกใครฆ่า: ${v}ทำภารกิจส่วนตัวไม่ทันกำหนด และร่างกายทรุดลงที่${zone.name}ในวันที่ ${day}  ไม่มีคนร้ายในคดีนี้`
      : cause === 'trap'
        ? `${k}วางกับดักด้วย${wname}ไว้ที่${zone.name} และ${v}เป็นคนแรกที่เข้ามาโดนในวันที่ ${day}  ${k}ไม่ได้อยู่ในห้องตอนที่${v}ตาย`
        : cause === 'defense'
          ? `${v}เป็นฝ่ายลงมือทำร้าย${k}ก่อนที่${zone.name}ในวันที่ ${day}  แต่${k}สวนกลับได้และ${v}กลับเป็นฝ่ายตาย ตามกติกาของที่นี่ ${k}จึงนับเป็นคนร้ายของคดี`
          : cause === 'wrongTarget'
            ? `${k}ตั้งใจลงมือกับคนอื่นที่${zone.name}ในวันที่ ${day}  แต่พลาดไปโดน${v}แทน${wname ? `ด้วย${wname}` : ''}`
            : `${k}ลงมือกับ${v}ที่${zone.name}ในวันที่ ${day} ${wname ? `ด้วย${wname}` : 'ด้วยมือเปล่า'}${messy ? ' แบบเลอะเทอะ ทิ้งร่องรอยไว้หลายจุด' : ' อย่างเงียบเชียบ'}${moved ? ' แล้วย้ายศพในภายหลัง' : ''}`;
  return { title, bodyState, sceneNotes, truthSummary };
}
